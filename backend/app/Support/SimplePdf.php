<?php

namespace App\Support;

class SimplePdf
{
    public static function make(string $title, array $headers, array $rows, array $metadata = []): string
    {
        $lines = [self::clean($title), str_repeat('=', min(strlen($title), 72))];

        foreach ($metadata as $label => $value) {
            if ($value !== null && $value !== '') {
                $lines[] = self::clean((string) $label).': '.self::clean((string) $value);
            }
        }

        $lines[] = 'Rows: '.count($rows);
        $lines[] = str_repeat('-', 92);
        $lines[] = implode(' | ', array_map(fn ($header) => self::clean((string) $header), $headers));
        $lines[] = str_repeat('-', 92);

        foreach (array_slice($rows, 0, 42) as $row) {
            $lines[] = self::clean(implode(' | ', array_map(fn ($value) => (string) $value, $row)));
        }

        if (count($rows) > 42) {
            $lines[] = '... '.(count($rows) - 42).' rows truncated. Use CSV export for full data.';
        }

        $lines[] = str_repeat('-', 92);
        $lines[] = 'Generated by TuneBoss Inventory';

        $content = "BT\n/F1 10 Tf\n50 790 Td\n";
        foreach ($lines as $index => $line) {
            $prefix = $index === 0 ? '' : '0 -16 Td ';
            $content .= $prefix.'('.self::escape(substr($line, 0, 115)).") Tj\n";
        }
        $content .= "ET\n";

        $objects = [
            '1 0 obj << /Type /Catalog /Pages 2 0 R >> endobj',
            '2 0 obj << /Type /Pages /Kids [3 0 R] /Count 1 >> endobj',
            '3 0 obj << /Type /Page /Parent 2 0 R /MediaBox [0 0 612 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >> endobj',
            '4 0 obj << /Type /Font /Subtype /Type1 /BaseFont /Courier >> endobj',
            '5 0 obj << /Length '.strlen($content)." >> stream\n".$content."endstream endobj",
        ];

        $pdf = "%PDF-1.4\n";
        $offsets = [0];
        foreach ($objects as $object) {
            $offsets[] = strlen($pdf);
            $pdf .= $object."\n";
        }

        $xrefOffset = strlen($pdf);
        $pdf .= "xref\n0 ".(count($objects) + 1)."\n";
        $pdf .= "0000000000 65535 f \n";
        foreach (array_slice($offsets, 1) as $offset) {
            $pdf .= str_pad((string) $offset, 10, '0', STR_PAD_LEFT)." 00000 n \n";
        }
        $pdf .= "trailer << /Size ".(count($objects) + 1)." /Root 1 0 R >>\n";
        $pdf .= "startxref\n{$xrefOffset}\n%%EOF";

        return $pdf;
    }

    private static function clean(string $value): string
    {
        return preg_replace('/[^\x20-\x7E]/', '?', $value) ?? '';
    }

    private static function escape(string $value): string
    {
        return str_replace(['\\', '(', ')'], ['\\\\', '\\(', '\\)'], $value);
    }
}
